/** Original map layer: draws recovered legacy map tiles at native pixels.

Tiles come from src/assets/map0.json, generated by
scripts/asset_tools/build_map_manifest.py from the local original client.
Each sprite sits at its measured grid position (x, y in map pixels). The
map is drawn in pixel space and is not converted to server tiles here; the
server still owns positions. Nothing is invented: a missing tile fails the
load instead of showing placeholder art.
*/
import { Assets, Container, Sprite, Texture } from 'pixi.js';
import mapManifest from '../assets/map0.json';

interface MapTile {
  id: string;
  x: number;
  y: number;
  width: number;
  height: number;
  url: string;
  sha256: string;
}

interface MapManifest {
  name: string;
  mapwidth: number;
  mapheight: number;
  tiles: MapTile[];
}

const manifest = mapManifest as MapManifest;

export class MapLayer {
  readonly root = new Container();

  /** Load every tile texture and place it at its measured position. */
  async load(): Promise<void> {
    const loads = manifest.tiles.map(async (tile) => {
      const texture: Texture = await Assets.load(tile.url);
      const sprite = new Sprite(texture);
      sprite.position.set(tile.x, tile.y);
      sprite.width = tile.width;
      sprite.height = tile.height;
      this.root.addChild(sprite);
    });
    await Promise.all(loads);
  }

  get pixelWidth(): number {
    return manifest.mapwidth;
  }

  get pixelHeight(): number {
    return manifest.mapheight;
  }

  get name(): string {
    return manifest.name;
  }
}
