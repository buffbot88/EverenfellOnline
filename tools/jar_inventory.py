"""Inventory the Java game jar: which class/method handles or sends each command.

Emits machine-readable JSON plus a readable Markdown command map. Built from
bytecode with tools/javap.py's parser, so the map is evidence, not guesswork.

Usage: jar_inventory.py <jar> [--limit N] [--json OUT] [--md OUT]
"""
import importlib.util
import json
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_spec = importlib.util.spec_from_file_location(
    'javap', os.path.join(ROOT, 'tools', 'javap.py'))
javap = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(javap)

# Command IDs on the wire are strings of 3-7 digits ('10001' .. '111000').
CMD_RE = re.compile(r"^'(\d{3,7})'$")
QUOTED_RE = re.compile(r"'([^']*)'")

MODULE_KINDS = ('Commands', 'Action', 'ServiceImpl', 'Output', 'Dao', 'DAO')


def module_kind(class_name):
    tail = class_name.rsplit('.', 1)[-1]
    for kind in MODULE_KINDS:
        if tail.endswith(kind):
            return kind
    return None


def scan_class(data):
    """Return (class_name, commands, refs) for one class file."""
    this, cp, cp_str, fields, methods = javap.parse_class(data)
    commands = {}
    for name, desc, code in methods:
        if not code:
            continue
        for line in javap.disasm(code, cp_str):
            for quoted in QUOTED_RE.findall(line):
                m = CMD_RE.match(f"'{quoted}'")
                if m:
                    commands.setdefault(m.group(1), []).append(name)
    refs = sorted({cp_str(i) for i, e in enumerate(cp)
                   if e and e[0] == 'Class' and cp_str(i).startswith('com.')
                   and not cp_str(i).startswith('com.jpexs')})
    return this, commands, refs


def build(jar_path, limit=None):
    with zipfile.ZipFile(jar_path) as z:
        names = [n for n in z.namelist() if n.endswith('.class')
                 and n.startswith('com/')]
        names.sort()
        if limit:
            names = names[:limit]
        by_cmd, modules, errors = {}, [], []
        for name in names:
            try:
                this, commands, refs = scan_class(z.read(name))
            except Exception as exc:
                errors.append(f'{name}: {exc}')
                continue
            kind = module_kind(this)
            if kind:
                modules.append({'class': this, 'kind': kind,
                                'methods': commands, 'refs': refs})
            for cmd, where in commands.items():
                by_cmd.setdefault(cmd, []).append({'class': this,
                                                   'methods': sorted(set(where)),
                                                   'kind': kind})
    return by_cmd, modules, errors


def write_markdown(out_path, by_cmd, modules, errors):
    # Wire command IDs are 5-6 digits (10001..111000). Three-digit strings are
    # error codes and enum values (RoleErrorCode '000', EffectType '101'), so
    # they stay in the JSON but are kept out of the command map.
    real = [c for c in by_cmd if len(c) >= 4]
    noise = [c for c in by_cmd if len(c) < 4]
    lines = ['# Java command map (generated by tools/jar_inventory.py)', '',
             'Every command ID found in server bytecode and the class/method that',
             'uses it. Regenerate rather than hand-editing.', '',
             f'Commands found: **{len(by_cmd)}** '
             f'(**{len(real)}** usable; {len(noise)} short numeric strings excluded',
             'as enum/error codes). Module classes: '
             f'**{len(modules)}**.',
             '']
    for cmd in sorted(real, key=int):
        lines.append(f'## `{cmd}`')
        for entry in by_cmd[cmd]:
            kind = entry['kind'] or 'other'
            lines.append(f"- `{entry['class']}` ({kind}) :: "
                         + ', '.join(f'`{m}()`' for m in entry['methods']))
        lines.append('')
    if noise:
        lines.append('## Excluded short IDs (enum/error codes, not commands)')
        lines.append('`' + '`, `'.join(sorted(noise, key=int)) + '`')
        lines.append('')
    if errors:
        lines.append('## Parse errors')
        lines += [f'- {e}' for e in errors]
        lines.append('')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(lines))


def main():
    jar = sys.argv[1]
    limit = None
    if '--limit' in sys.argv:
        limit = int(sys.argv[sys.argv.index('--limit') + 1])
    json_out = (sys.argv[sys.argv.index('--json') + 1] if '--json' in sys.argv
                else os.path.join(ROOT, 'output', 'jar-inventory.json'))
    md_out = (sys.argv[sys.argv.index('--md') + 1] if '--md' in sys.argv
              else os.path.join(ROOT, 'docs', 'java-command-map.md'))
    by_cmd, modules, errors = build(jar, limit)
    os.makedirs(os.path.dirname(json_out), exist_ok=True)
    with open(json_out, 'w', encoding='utf-8', newline='\n') as out:
        json.dump({'commands': by_cmd, 'modules': modules, 'errors': errors},
                  out, indent=1, ensure_ascii=False)
    write_markdown(md_out, by_cmd, modules, errors)
    print(f'commands={len(by_cmd)} modules={len(modules)} errors={len(errors)}')
    print(f'json: {json_out}')
    print(f'markdown: {md_out}')


if __name__ == '__main__':
    main()
